"""Asset definition and writers for textures, models, CREDITS.md and the generated-file manifest."""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path

from PIL import Image

from .atlas import Atlas
from .model import Model

AUTHOR = "vxnsin, mit KI-Unterstützung erzeugt"
SOURCE = "tools/generate_assets.py"
LICENSE = "CC BY 4.0"
CHANGES = "Platzhalter"

CREDITS_START = "<!-- assetgen:start -->"
CREDITS_END = "<!-- assetgen:end -->"
MANIFEST = ".assetgen-manifest"


@dataclass
class Asset:
    """One textured object. `models` maps a file suffix ("" = main model, e.g. "_aim") to a model."""

    id: str
    category: str  # item | furniture | sign
    title: str  # German title for CREDITS.md
    atlas: Atlas
    models: dict[str, Model] = field(default_factory=dict)

    @property
    def texture_ref(self) -> str:
        return f"lna:{self.category}/{self.id}"


class Output:
    """Writes generated files below content/ and remembers them for credits and stale-file cleanup."""

    def __init__(self, content_dir: Path) -> None:
        self.content_dir = content_dir
        self.written: list[tuple[str, str]] = []  # (path relative to content/, credits title)

    def image(self, relative: str, image: Image.Image, title: str) -> None:
        path = self._path(relative)
        image.save(path, optimize=True)
        self.written.append((relative, title))

    def json(self, relative: str, data: dict, title: str) -> None:
        self._path(relative).write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n",
                                        encoding="utf-8", newline="\n")
        self.written.append((relative, title))

    def file(self, relative: str, title: str) -> Path:
        """Reserves a path for a file written by the caller (e.g. audio)."""
        self.written.append((relative, title))
        return self._path(relative)

    def asset(self, asset: Asset) -> None:
        image, uvs = asset.atlas.build()
        self.image(f"textures/{asset.category}/{asset.id}.png", image, f"{asset.title} (Textur)")
        for suffix, model in asset.models.items():
            variant = {"": "", "_draw": ", Schlauch ziehen", "_aim": ", zielen"}.get(suffix, f", {suffix}")
            self.json(f"models/{asset.category}/{asset.id}{suffix}.json",
                      model.to_json(asset.texture_ref, uvs, image.width),
                      f"{asset.title} (3D-Modell{variant})")

    def finish(self, credits_file: Path) -> list[str]:
        """Updates the generated credits table and removes files generated by a previous run but not this one."""
        manifest = self.content_dir / MANIFEST
        current = sorted(path for path, _ in self.written)
        removed = []
        if manifest.exists():
            for old in manifest.read_text(encoding="utf-8").split():
                if old not in current and (self.content_dir / old).exists():
                    (self.content_dir / old).unlink()
                    removed.append(old)
        manifest.write_text("\n".join(current) + "\n", encoding="utf-8", newline="\n")
        self._write_credits(credits_file)
        return removed

    def _write_credits(self, credits_file: Path) -> None:
        rows = [
            "| Datei | Titel | Urheber*in | Quelle | Lizenz | Änderungen |",
            "|---|---|---|---|---|---|",
            *(f"| {path} | {title} | {AUTHOR} | {SOURCE} | {LICENSE} | {CHANGES} |"
              for path, title in sorted(self.written)),
        ]
        block = "\n".join([CREDITS_START, *rows, CREDITS_END])
        text = credits_file.read_text(encoding="utf-8")
        if CREDITS_START in text and CREDITS_END in text:
            before = text[:text.index(CREDITS_START)]
            after = text[text.index(CREDITS_END) + len(CREDITS_END):]
            text = before + block + after
        else:
            text = text.rstrip() + "\n\n## Generierte Assets\n\n" + block + "\n"
        credits_file.write_text(text, encoding="utf-8", newline="\n")

    def _path(self, relative: str) -> Path:
        path = self.content_dir / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        return path
