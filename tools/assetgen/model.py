"""Java item model builder: cuboids, element rotations and display presets with automatic fitting."""

from __future__ import annotations

import math
from dataclasses import dataclass

FACES = ("north", "east", "south", "west", "up", "down")
ALLOWED_ANGLES = (-45.0, -22.5, 0.0, 22.5, 45.0)
COORDINATE_RANGE = (-16.0, 32.0)

Vec3 = tuple[float, float, float]


@dataclass(frozen=True)
class Cuboid:
    name: str
    start: Vec3
    end: Vec3
    faces: dict[str, str]
    rotation: dict | None


class Model:
    """A Java item model made of cuboids. Faces reference atlas tiles by name.

    Convention: the front of wall-mounted objects is the north face (towards -z).
    """

    def __init__(self, preset: str) -> None:
        if preset not in PRESETS:
            raise ValueError(f"unknown display preset '{preset}'")
        self.preset = preset
        self.elements: list[Cuboid] = []

    def box(self, name: str, start: Vec3, end: Vec3, material: str, *,
            rotation: tuple[str, float, Vec3] | None = None, **faces: str | None) -> Model:
        """Adds a cuboid. `material` covers all faces; keyword arguments override single faces (None hides one)."""
        for low, high in zip(start, end):
            if low > high or low < COORDINATE_RANGE[0] or high > COORDINATE_RANGE[1]:
                raise ValueError(f"{name}: invalid bounds {start} -> {end}")
        unknown = set(faces) - set(FACES)
        if unknown:
            raise ValueError(f"{name}: unknown faces {unknown}")
        face_map = {face: material for face in FACES}
        face_map.update(faces)
        rotation_json = None
        if rotation is not None:
            axis, angle, origin = rotation
            if angle not in ALLOWED_ANGLES:
                raise ValueError(f"{name}: rotation angle must be one of {ALLOWED_ANGLES}")
            rotation_json = {"angle": angle, "axis": axis, "origin": list(origin)}
        self.elements.append(Cuboid(name, tuple(start), tuple(end),
                                    {f: m for f, m in face_map.items() if m is not None}, rotation_json))
        return self

    def materials(self) -> set[str]:
        return {material for element in self.elements for material in element.faces.values()}

    def bounds(self) -> tuple[Vec3, Vec3]:
        low = tuple(min(e.start[i] for e in self.elements) for i in range(3))
        high = tuple(max(e.end[i] for e in self.elements) for i in range(3))
        return low, high

    def to_json(self, texture: str, uvs: dict[str, list[float]], texture_size: int) -> dict:
        missing = self.materials() - uvs.keys()
        if missing:
            raise ValueError(f"materials without atlas tile: {sorted(missing)}")
        elements = []
        for element in self.elements:
            data = {"name": element.name, "from": list(element.start), "to": list(element.end)}
            if element.rotation:
                data["rotation"] = element.rotation
            data["faces"] = {face: {"uv": uvs[material], "texture": "#atlas"}
                             for face, material in element.faces.items()}
            elements.append(data)
        return {
            "credit": "Lass nichts anbrennen - generated by tools/generate_assets.py",
            "texture_size": [texture_size, texture_size],
            "textures": {"atlas": texture, "particle": texture},
            "elements": elements,
            "display": PRESETS[self.preset](self.bounds()),
        }


# ---------------------------------------------------------------------------------------------
# Display transforms
#
# Minecraft applies: translate, then rotate (XYZ, i.e. R = Rx * Ry * Rz), then scale, around the
# model center (8, 8, 8). `_transform` adds a translation that moves the bounding box center of the
# model to the display origin, so off-center or oversized models still sit correctly.
# Left-hand transforms follow the vanilla convention: rotation y and z negated.
# ---------------------------------------------------------------------------------------------

def _rotation_matrix(rx: float, ry: float, rz: float) -> list[list[float]]:
    x, y, z = (math.radians(a) for a in (rx, ry, rz))
    mx = [[1, 0, 0], [0, math.cos(x), -math.sin(x)], [0, math.sin(x), math.cos(x)]]
    my = [[math.cos(y), 0, math.sin(y)], [0, 1, 0], [-math.sin(y), 0, math.cos(y)]]
    mz = [[math.cos(z), -math.sin(z), 0], [math.sin(z), math.cos(z), 0], [0, 0, 1]]

    def mul(a: list[list[float]], b: list[list[float]]) -> list[list[float]]:
        return [[sum(a[i][k] * b[k][j] for k in range(3)) for j in range(3)] for i in range(3)]

    return mul(mul(mx, my), mz)


def _transform(rotation: Vec3, scale: float, center: Vec3, offset: Vec3 = (0, 0, 0)) -> dict:
    matrix = _rotation_matrix(*rotation)
    local = [(c - 8) * scale for c in center]
    moved = [sum(matrix[i][k] * local[k] for k in range(3)) for i in range(3)]
    translation = [max(-80.0, min(80.0, round(offset[i] - moved[i], 2))) for i in range(3)]
    scale = round(min(4.0, scale), 3)
    return {"rotation": list(rotation), "translation": translation, "scale": [scale, scale, scale]}


def _mirror(transform: dict) -> dict:
    rx, ry, rz = transform["rotation"]
    return {**transform, "rotation": [rx, -ry, -rz]}


def _dims(bounds: tuple[Vec3, Vec3]) -> tuple[Vec3, float]:
    low, high = bounds
    center = tuple((low[i] + high[i]) / 2 for i in range(3))
    size = max(high[i] - low[i] for i in range(3))
    return center, max(size, 1.0)


def _preset(gui_rotation: Vec3, gui_fill: float, hand_third: tuple[Vec3, float, Vec3],
            hand_first: tuple[Vec3, float, Vec3], fixed_rotation: Vec3, ground_scale: float):
    """Creates a preset function. Hand scales are relative to a 16-unit model and shrink larger models."""

    def build(bounds: tuple[Vec3, Vec3]) -> dict:
        center, size = _dims(bounds)
        fit = min(1.0, 16 / size)
        third = _transform(hand_third[0], hand_third[1] * fit, center, hand_third[2])
        first = _transform(hand_first[0], hand_first[1] * fit, center, hand_first[2])
        return {
            "thirdperson_righthand": third,
            "thirdperson_lefthand": _mirror(third),
            "firstperson_righthand": first,
            "firstperson_lefthand": _mirror(first),
            "gui": _transform(gui_rotation, gui_fill / size, center),
            "ground": _transform((0, 0, 0), ground_scale * fit, center, (0, 3, 0)),
            "fixed": _transform(fixed_rotation, 14 / size, center),
            "head": _transform((0, 0, 0), 0.8 * fit, center, (0, -2, 0)),
        }

    return build


PRESETS = {
    # Carried upright (extinguishers, spray can): hose side faces the camera in first person.
    "upright": _preset((15, -35, 0), 14.5, ((0, -90, 0), 0.5, (0, 0, 1)),
                       ((0, -75, 0), 0.45, (1.5, 0.5, -1)), (0, 180, 0), 0.35),
    # While spraying: model +x (hose/nozzle direction) points forward, raised to chest height.
    "aim": _preset((15, -35, 0), 14.5, ((0, -90, 0), 0.5, (0, 2.5, 2)),
                   ((0, 95, 0), 0.45, (-1, 3, -2)), (0, 180, 0), 0.35),
    # Small handheld objects (phone, battery, charger, lid).
    "small": _preset((25, -40, 0), 12.5, ((0, -90, 0), 0.6, (0, 2, 1)),
                     ((0, -60, 0), 0.6, (1, 2, 0)), (0, 180, 0), 0.4),
    # Thin plates whose front is the north face (cards, clipboards, signs).
    "flat": _preset((0, 180, 0), 14.0, ((0, 180, 0), 0.5, (0, 1, 0.5)),
                    ((0, 170, 0), 0.5, (0, 2, 0)), (0, 180, 0), 0.4),
    # Block-like furniture, vanilla block/block angles.
    "block": _preset((30, 225, 0), 10.0, ((75, 45, 0), 0.375, (0, 2.5, 0)),
                     ((0, 45, 0), 0.4, (0, 0, 0)), (0, 0, 0), 0.25),
    # Wall-mounted objects (front = north face, back at z = 16).
    "wall": _preset((0, 180, 0), 13.0, ((75, 45, 0), 0.375, (0, 2.5, 0)),
                    ((0, 45, 0), 0.4, (0, 0, 0)), (0, 180, 0), 0.25),
}
